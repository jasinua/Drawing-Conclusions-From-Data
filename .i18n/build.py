#!/usr/bin/env python3
"""Builds i18n-sq.js from the .tsv parts (English <TAB> Albanian). Run from the repo root."""
import glob, json, re
exact, rules = {}, []
for f in sorted(glob.glob('.i18n/part*.tsv')):
    for line in open(f, encoding='utf-8'):
        line = line.rstrip('\n')
        if not line.strip(): continue
        en, sq = line.split('\t', 1)
        en = re.sub(r'\s+', ' ', en.strip()); sq = sq.strip()
        if en.startswith('~'):
            rules.append([en[1:], sq])
        elif '{{' in en:
            pat = '^' + re.sub(r'\\\{\\\{ .+? \\\}\\\}', '(.+?)', re.escape(en)) + '$'
            rules.append([pat, re.sub(r'\{(\d)\}', lambda m: '$' + str(int(m.group(1)) + 1), sq)])
        else:
            exact[en] = sq
out = '/* Albanian dictionary, generated by .i18n/build.py. Edit the .tsv files, not this file. */\nwindow.I18N_SQ = ' + json.dumps({'exact': exact, 'rules': rules}, ensure_ascii=False, indent=0) + ';\n'
open('i18n-sq.js', 'w', encoding='utf-8').write(out)
print(len(exact), 'exact,', len(rules), 'rules')
